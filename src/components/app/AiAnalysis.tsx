import { api } from "@/convex/_generated/api";
import { cn } from "@/lib/utils";
import { useAction } from "convex/react";
import { AlertTriangle, RefreshCw, Sparkles } from "lucide-react";
import { useCallback, useEffect, useRef, useState } from "react";
import { btnPrimary, Card, PanelTitle } from "./ui";

/* ── North Mini analysis panel ───────────────────────────────────────────
   Every "analysis" surface in the product renders through this component:
   the page supplies the computed stats (counts, severities, series), and the
   North Mini model — via the project's AI gateway — produces the actual
   analysis text. No local template narratives: the model is the analyst. */

type Status = "idle" | "running" | "done" | "error";
type Args = { task: string; context: string; question?: string };
type AnalysisResult = { ok: boolean; text: string; model: string; credits?: number; error?: string };

export function AiAnalysis({
  task,
  context,
  question,
  title,
  sub,
  auto = false,
  className = "",
}: {
  /** What is being analysed, e.g. "portfolio risk overview". */
  task: string;
  /** Structured stats computed by the page — serialized to JSON for the model. */
  context: Record<string, unknown>;
  /** Optional focused question to steer the analysis. */
  question?: string;
  title?: string;
  sub?: string;
  /** Run once on mount instead of waiting for the button. */
  auto?: boolean;
  className?: string;
}) {
  const analyze = useAction(api.ai.analyze);
  const [status, setStatus] = useState<Status>(auto ? "running" : "idle");
  const [text, setText] = useState("");
  const [error, setError] = useState("");

  // Latest props live in a ref so `run`/`buildArgs` stay stable — otherwise an
  // auto-run effect would re-fire on every re-render of the page. The ref is
  // synced in an effect (never during render).
  const argsRef = useRef({ task, context, question });
  useEffect(() => {
    argsRef.current = { task, context, question };
  });

  const buildArgs = useCallback(
    (): Args => ({
      task: argsRef.current.task,
      context: JSON.stringify(argsRef.current.context).slice(0, 60_000),
      question: argsRef.current.question,
    }),
    [],
  );

  const apply = useCallback((res: AnalysisResult) => {
    if (res.ok && res.text) {
      setText(res.text);
      setStatus("done");
    } else {
      setError(res.error || "The model returned no analysis.");
      setStatus("error");
    }
  }, []);

  /** Manual re-run (button) — event handlers may set state synchronously. */
  const run = useCallback(async () => {
    setStatus("running");
    setError("");
    try {
      apply(await analyze(buildArgs()));
    } catch (e) {
      setError(e instanceof Error ? e.message : "Analysis request failed.");
      setStatus("error");
    }
  }, [analyze, apply, buildArgs]);

  // Auto-run once per mount (StrictMode's repeated effect pass is ignored via
  // `started`); the result lands in promise callbacks, not in the effect body.
  const started = useRef(false);
  useEffect(() => {
    if (!auto || started.current) return;
    started.current = true;
    analyze(buildArgs())
      .then(apply)
      .catch((e: unknown) => {
        setError(e instanceof Error ? e.message : "Analysis request failed.");
        setStatus("error");
      });
  }, [auto, analyze, buildArgs, apply]);

  const busy = status === "running";

  return (
    <Card className={cn("overflow-hidden", className)}>
      <PanelTitle
        title={title ?? "AI analysis"}
        sub={sub ?? "Generated by North Mini from the figures on this page"}
        right={
          <button
            onClick={() => void run()}
            disabled={busy}
            className={cn(btnPrimary, "shrink-0 px-3 py-1.5 text-xs")}
          >
            {busy ? (
              <RefreshCw className="h-3.5 w-3.5 animate-spin" />
            ) : (
              <Sparkles className="h-3.5 w-3.5" />
            )}
            {status === "done" ? "Re-run" : busy ? "Analysing…" : "Run analysis"}
          </button>
        }
      />

      <div className="px-5 pb-4 pt-3">
        {status === "idle" && (
          <p className="text-[13px] leading-6 text-muted-foreground">
            North Mini reads the metrics on this page and writes the analysis: what stands out,
            what it could mean, and what the data cannot tell you.
          </p>
        )}

        {busy && (
          <div className="space-y-2" aria-live="polite">
            <div className="flex items-center gap-2 text-[13px] text-[#c4b5fd]">
              <Sparkles className="h-3.5 w-3.5 animate-pulse" />
              North Mini is analysing…
            </div>
            <div className="h-2.5 w-11/12 animate-pulse rounded bg-muted" />
            <div className="h-2.5 w-10/12 animate-pulse rounded bg-muted" />
            <div className="h-2.5 w-8/12 animate-pulse rounded bg-muted" />
          </div>
        )}

        {status === "done" && <AiText text={text} />}

        {status === "error" && (
          <div className="flex items-start gap-2.5 rounded-xl border border-[color:var(--destructive)]/35 bg-[color:var(--destructive)]/10 px-4 py-3 text-[13px] leading-6">
            <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0 text-[color:var(--destructive)]" />
            <p className="text-foreground">
              <span className="font-semibold">Analysis unavailable.</span>{" "}
              <span className="text-muted-foreground">{error}</span>
            </p>
          </div>
        )}
      </div>

      {(status === "done" || status === "error") && (
        <p className="mono border-t border-border/60 px-5 py-2 text-[10px] leading-4 text-muted-foreground">
          model: cohere/north-mini-code (North Mini) · figures are computed by the platform — the
          model interprets them
        </p>
      )}
    </Card>
  );
}

/** Minimal markdown renderer: ## headings, bullets, **bold** — nothing else. */
function AiText({ text }: { text: string }) {
  const blocks: string[] = [];
  let current = "";
  for (const line of text.split("\n")) {
    if (line.trim() === "") {
      if (current) blocks.push(current);
      current = "";
    } else current = current ? `${current}\n${line}` : line;
  }
  if (current) blocks.push(current);

  return (
    <div className="space-y-3 text-[13px] leading-6" aria-live="polite">
      {blocks.map((b, i) => {
        const heading = b.match(/^##?\s+(.*)$/);
        if (heading)
          return (
            <p key={i} className="display pt-0.5 text-[13px] font-semibold tracking-tight text-foreground">
              {inline(heading[1])}
            </p>
          );
        const bullets = b.split("\n");
        if (bullets.every((l) => /^\s*[-*•]\s+/.test(l)))
          return (
            <ul key={i} className="space-y-1">
              {bullets.map((l, j) => (
                <li key={j} className="flex gap-2">
                  <span className="mt-2 h-1 w-1 shrink-0 rounded-full bg-[color:var(--primary)]" />
                  <span className="text-muted-foreground">{inline(l.replace(/^\s*[-*•]\s+/, ""))}</span>
                </li>
              ))}
            </ul>
          );
        return <p key={i} className="text-muted-foreground">{inline(b)}</p>;
      })}
    </div>
  );
}

/** Renders **bold** spans without dangerouslySetInnerHTML. */
function inline(s: string) {
  const parts = s.split(/(\*\*[^*]+\*\*)/g);
  return parts.map((p, i) =>
    p.startsWith("**") && p.endsWith("**") && p.length > 4 ? (
      <strong key={i} className="font-semibold text-foreground">
        {p.slice(2, -2)}
      </strong>
    ) : (
      <span key={i}>{p}</span>
    ),
  );
}
